#!/usr/bin/env python3
"""Embed the v4 web UI into the firmware as gzipped PROGMEM arrays.

    python3 webui/build-assets.py          (from the repo root)

Reads webui/index.html, writes UppityFirmware/src/arduino/WebAssets.h. Run after ANY change
to index.html, then recompile. Why PROGMEM instead of a filesystem: one generated header, so
the sketch compiles and flashes with no filesystem-uploader step and no way for code and page
to drift apart (Sabé's approach, docs/REWRITE-PLAN.md Appendix C.1). The build id is a hash
of the UNCOMPRESSED bytes and becomes the ETag, so a phone revalidates for free after an OTA
instead of showing a stale page.
"""
import gzip, hashlib, pathlib

WEBUI = pathlib.Path(__file__).resolve().parent
OUT = WEBUI.parent / "UppityFirmware" / "src" / "arduino" / "WebAssets.h"
FILES = [("/", "text/html", WEBUI / "index.html")]

def c_array(name, blob):
    lines = [f"static const uint8_t {name}[] PROGMEM = {{"]
    for i in range(0, len(blob), 24):
        lines.append("  " + ",".join(str(b) for b in blob[i:i + 24]) + ",")
    lines.append("};")
    return "\n".join(lines)

def main():
    arrays, entries, raws = [], [], []
    for i, (url, mime, src) in enumerate(FILES):
        raw = src.read_bytes(); gz = gzip.compress(raw, 9); raws.append(raw)
        name = f"UPPITY_ASSET_{i}"
        arrays.append(c_array(name, gz)); entries.append((url, mime, name, len(gz)))
        print(f"  {url:<12} {len(raw):>8,} -> {len(gz):>8,} gz")
    build_id = hashlib.sha1(b"".join(raws)).hexdigest()[:12]
    table = ",\n".join(f'  {{ "{u}", "{m}", {n}, {l} }}' for u, m, n, l in entries)
    OUT.write_text(
        "// GENERATED by webui/build-assets.py from webui/index.html. Do not edit; re-run the script.\n"
        "#pragma once\n#include <pgmspace.h>\n\n"
        "struct WebAsset { const char* path; const char* mime; const uint8_t* data; unsigned int len; };  // gzip-compressed\n\n"
        + "\n\n".join(arrays)
        + f"\n\nstatic const WebAsset WEB_ASSETS[] = {{\n{table}\n}};\n"
        + f"static const unsigned int WEB_ASSET_COUNT = {len(entries)};\n"
        + f'#define WEB_ASSETS_BUILD "{build_id}"\n', encoding="utf-8")
    print(f"  build id {build_id} -> {OUT.relative_to(WEBUI.parent)}")

if __name__ == "__main__":
    main()
